#!/usr/bin/env python3
# seed-runner.py - P-07 seed bank calibration runner.
# Steps:
#   1. Validate the calibration record header: model ID, prompt hash,
#      and checklist hash are all required. A record without any one of
#      them is VOID and the run stops (exit 2). Calibration runs blind
#      at least every 10th production pass and after any model, prompt,
#      or checklist change.
#   2. Copy the fixture artifact to an isolated review copy. Seeds are
#      injected ONLY into the copy, never the shipping tree. Bank
#      target paths are written bank-relative (fixture-app/<lens>/
#      module-NN.txt); pass --artifact as the fixture-app directory
#      itself and the runner strips the leading fixture-app component
#      when resolving targets inside the copy. The fixture is
#      generated by make-fixture.py: every module file carries
#      exactly 12 clean lines, so each seed's defect lands on the
#      line the ground truth declares. The runner VERIFIES that
#      arithmetic per seed at injection time and refuses to score
#      (exit 2) when the injected line disagrees with the ground
#      truth: bank, fixture, or truth drift is a loud failure, never
#      a silent mis-score.
#   3. Custody: the ground truth is the oracle and must be held
#      OUTSIDE the ingested tree. If the ground-truth path resolves
#      inside the artifact under review, the run is marked INVALID in
#      the report (custody_ok false) with a warning: a panel that can
#      read the oracle is not being measured.
#   4. Run the critic command once per critic (the command receives
#      the review-copy path and the critic id as its last two
#      arguments and prints finding lines). A finding line scores only
#      when it names the seed's target file, a line within 3 of the
#      defect line, and the defect class token (or its space or
#      underscore form). A bare seed-ID string in the output scores
#      nothing: the bank carries no markers in the review copy, so
#      there is nothing to grep for.
#   5. The built-in fixture critic (--use-fixture-critic) detects the
#      planted patterns with a per-class signature table (DETECTORS
#      below): a route handler with no auth token in its block, SQL
#      built by concatenation, a percentage with no provenance marker,
#      a tap target under 44px, consent language, and so on, plus one
#      cross-file check (a quotation that strengthens an earlier
#      quotation of the same passage). It proves the harness plumbing
#      end to end: injection, detection, scoring. It is NOT evidence
#      about a real panel: a signature table written against the
#      bank's own classes will of course catch the bank, and a perfect
#      fixture score must never be quoted as panel skill. The report
#      says so on its face.
#   6. Score against the ground truth: catch per lens, per severity,
#      per critic, and panel union. Report-first: this runner reports;
#      it does not gate. Calibration earns gate status only with
#      measured history.
# Exit codes: 0 run completed and report printed; 1 run completed with
# zero panel-union catch (harness sanity failure); 2 void record,
# ground-truth drift, or runner could not run.
# Python 3 standard library only.
import argparse, json, re, shutil, subprocess, sys, tempfile
from pathlib import Path

LINE_WINDOW = 3

def _rx(pattern, flags=re.I):
    rx = re.compile(pattern, flags)
    return lambda lines, rel: [(i + 1) for i, l in enumerate(lines) if rx.search(l)]

def _block_missing_auth(lines, rel):
    hits = []
    auth = re.compile(r"require_auth|authenticate|authorize|login_required|check_permission|permission_required", re.I)
    route = re.compile(r"route\(|def\s+\w*(admin|delete|update|login)\w*\s*\(", re.I)
    for i, l in enumerate(lines):
        if route.search(l) and not any(auth.search(x) for x in lines[max(0, i - 1):i + 4]):
            hits.append(i + 1)
    return hits

def _block_missing_rate_limit(lines, rel):
    hits = []
    guard = re.compile(r"rate|throttle|limit|lockout|attempts", re.I)
    for i, l in enumerate(lines):
        if re.search(r"def\s+login\s*\(", l) and not any(guard.search(x) for x in lines[i:i + 4]):
            hits.append(i + 1)
    return hits

def _value_below(pattern, floor):
    rx = re.compile(pattern, re.I)
    def f(lines, rel):
        out = []
        for i, l in enumerate(lines):
            m = rx.search(l)
            if m and float(m.group(1)) < floor:
                out.append(i + 1)
        return out
    return f

def _no_provenance(pattern):
    rx = re.compile(pattern, re.I)
    prov = re.compile(r"\(source|n\s*=\s*\d|respondents|benchmark|measured by", re.I)
    def f(lines, rel):
        return [i + 1 for i, l in enumerate(lines) if rx.search(l) and not prov.search(l)]
    return f

DETECTORS = {
    # code
    "missing-auth-check": _block_missing_auth,
    "sql-string-concat": _rx(r"(SELECT|INSERT INTO|UPDATE|DELETE FROM).*(\+\s*\w|%\s*\(|\.format\(|f\")"),
    "shell-injection": _rx(r"os\.system\([^)]*(\+|f\")|shell\s*=\s*True"),
    "hardcoded-secret": lambda lines, rel: [i + 1 for i, l in enumerate(lines)
        if re.search(r"(api_key|secret|password|token|_KEY)\s*=\s*[\"'][^\"']{8,}[\"']", l, re.I)
        and not re.search(r"environ|getenv", l)],
    "unsafe-deserialize": _rx(r"pickle\.loads?\("),
    "path-traversal": _rx(r"open\([^)]*(req\.|request\.|args\[|params\[|form\[)"),
    "weak-crypto": _rx(r"(md5|sha1)\([^)]*pass", re.I),
    "missing-rate-limit": _block_missing_rate_limit,
    # claims
    "fabricated-statistic": _no_provenance(r"\d+(\.\d+)?\s*(percent|%) of"),
    "missing-provenance": _no_provenance(r"grew \d+(\.\d+)?x|fell by half|up \d+(\.\d+)?x"),
    "invented-citation": _rx(r"Journal of [A-Z][A-Za-z ]+ \(\d{4}\)"),
    "correlation-as-causation": _rx(r"\bcauses?\b[^.]*\d+(\.\d+)?\s*percent"),
    "cherry-picked-window": _rx(r"up \d+(\.\d+)? percent since (January|February|March|April|May|June|July|August|September|October|November|December) \d{4}"),
    "unbacked-superlative": _no_provenance(r"\b(fastest|best|leading)\b[^.]*\b(on the market|ever|in the world)\b"),
    "stale-figure-as-current": _rx(r"currently[^.]*\(20(19|20|21|22|23)\b"),
    # ux
    "missing-error-state": _rx(r"no error state|silently reloads"),
    "keyboard-trap": _rx(r"focus is trapped|traps focus|Esc key is disabled"),
    "tiny-touch-target": _value_below(r"tap target of (\d+(?:\.\d+)?)px", 44),
    "missing-alt-text": lambda lines, rel: [i + 1 for i, l in enumerate(lines)
        if (re.search(r"<img[^>]*>", l) and "alt=" not in l) or re.search(r"no alt attribute", l, re.I)],
    "color-only-status": _rx(r"by colou?r alone"),
    "low-contrast": _value_below(r"contrast ratio of (\d+(?:\.\d+)?) to 1", 4.5),
    "jargon-error-message": _rx(r"user sees the raw message|ERR_[A-Z_]+|0x[0-9a-fA-F]{2,}"),
    "missing-empty-state": _rx(r"no empty state is designed|blank panel"),
    # growth
    "missing-ad-disclosure": _rx(r"sponsored post with no disclosure|no disclosure label"),
    "fake-scarcity": _rx(r"only \d+ left at this price|selling fast"),
    "unsubstantiated-superlative": _rx(r"\b(best|fastest)\b[^.]*\b(ever|guaranteed|on the market)\b"),
    "dark-pattern-preselect": lambda lines, rel: [i + 1 for i, l in enumerate(lines)
        if re.search(r"pre-checked|pre-selected", l, re.I) and not re.search(r"consent", l, re.I)],
    "unbacked-comparison": _no_provenance(r"as fast as [A-Z]|than [A-Z][a-z]+"),
    "testimonial-without-source": _rx(r"testimonial.*withheld", re.I),
    "price-without-terms": lambda lines, rel: [i + 1 for i, l in enumerate(lines)
        if re.search(r"\$\d+ per month", l) and not re.search(r"introductory|intro rate|terms|renews at|after the intro", l, re.I)],
    "missing-brief-fit": _rx(r"audience is not specified|run the same creative for everyone"),
    # compliance
    "prechecked-consent": _rx(r"consent checkbox ships pre-checked|consent.*pre-checked"),
    "children-no-age-gate": _rx(r"children under 13[^.]*no age gate|no age gate or parental consent"),
    "retention-forever": _rx(r"retained indefinitely|kept forever"),
    "bundled-consent": _rx(r"you also agree to receive partner marketing"),
    "transfer-without-notice": _rx(r"overseas processor[^.]*does not mention|transferred[^.]*notice does not mention"),
    "breach-timeline-wrong": _rx(r"notified within 30 days of a confirmed breach|notify[^.]*within 30 days of a confirmed breach"),
    "missing-dpo-contact": _rx(r"intentionally omits any privacy contact|no privacy contact"),
    "missing-purpose": _rx(r"purpose is recorded nowhere"),
}

INTENSIFIERS = {"definitely", "guaranteed", "guarantee", "never", "always", "must", "will"}

def _quote_variants(copy_root):
    """Cross-file misquote check: a quotation that shares most of its
    words with an earlier quotation but adds intensifiers the earlier
    one does not carry is reported at its own line."""
    quotes = []
    for p in sorted(Path(copy_root).rglob("*")):
        if not p.is_file():
            continue
        rel = str(p.relative_to(copy_root))
        for i, line in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines()):
            for q in re.findall(r'"([^"]{30,})"', line):
                words = re.findall(r"[a-z]+", q.lower())
                if len(words) >= 6:
                    quotes.append((rel, i + 1, set(words), words))
    hits = []
    for rel, ln, wset, words in quotes:
        for orel, oln, owset, owords in quotes:
            if (rel, ln) == (orel, oln):
                continue
            shared = len(wset & owset)
            if shared >= 0.5 * min(len(wset), len(owset)) and wset != owset:
                if (wset - owset) & INTENSIFIERS:
                    hits.append((rel, ln))
                break
    return hits

def fixture_critic(copy_root, critic_id):
    found = []
    for p in sorted(Path(copy_root).rglob("*")):
        if not p.is_file():
            continue
        rel = str(p.relative_to(copy_root))
        lines = p.read_text(encoding="utf-8", errors="replace").splitlines()
        for cls, detect in DETECTORS.items():
            for ln in detect(lines, rel):
                found.append(f"FINDING {rel}:{ln} {cls}")
    for rel, ln in _quote_variants(copy_root):
        found.append(f"FINDING {rel}:{ln} misquoted-source")
    return found

def class_tokens(cls):
    return {cls, cls.replace("-", " "), cls.replace("-", "_")}

def score(lines, seed, truth_entry):
    target = seed["target_file"]
    want_line = int(truth_entry["location"].rsplit(":", 1)[1])
    tokens = class_tokens(seed["defect_class"])
    for l in lines:
        m = re.search(r"(\S+):(\d+)\b", l)
        if not m:
            continue
        path, ln = m.group(1), int(m.group(2))
        if not (path == target or path.endswith("/" + target) or target.endswith(path)):
            continue
        if abs(ln - want_line) > LINE_WINDOW:
            continue
        low = l.lower()
        if any(t.lower() in low for t in tokens):
            return True
    return False


MARKER_TOKENS = ("PLANTED", "SEEDED-DEFECT", "GROUND-TRUTH", "ORACLE")

def bank_hygiene_violations(bank):
    """A seed insertion may not announce itself: no seed_id, no marker
    tokens. A bank that fails hygiene is void (Lane 5 hygiene law): the
    v1 runner scored exactly these announcements as catches."""
    bad = []
    for s in bank["seeds"]:
        ins = s.get("insertion", "")
        if s["seed_id"] in ins or any(tok in ins for tok in MARKER_TOKENS):
            bad.append(s["seed_id"])
    return bad

def score_partial(lines, seed, truth_entry):
    """Near misses, never catches: classification-partial (right file and
    line window, wrong or absent class) and localization-partial (right
    class on the right file, outside the line window)."""
    target = seed["target_file"]
    want_line = int(truth_entry["location"].rsplit(":", 1)[1])
    tokens = class_tokens(seed["defect_class"])
    cls_partial = False
    for l in lines:
        m = re.search(r"(\S+):(\d+)\b", l)
        if not m:
            continue
        path, ln = m.group(1), int(m.group(2))
        if not (path == target or path.endswith("/" + target) or target.endswith(path)):
            continue
        has_class = any(t.lower() in l.lower() for t in tokens)
        if abs(ln - want_line) <= LINE_WINDOW:
            if not has_class:
                cls_partial = True
        elif has_class:
            return "localization-partial"
    return "classification-partial" if cls_partial else None

def legacy_substring_caught(lines, seed):
    """The v1 rule, kept for comparison only: the seed_id appearing as a
    substring of any output line. It counts marker visibility, not
    detection, and is never a catch."""
    return any(seed["seed_id"] in l for l in lines)

def main():
    ap = argparse.ArgumentParser(description="Seed bank calibration runner (P-07)")
    ap.add_argument("--bank", required=True)
    ap.add_argument("--ground-truth", required=True)
    ap.add_argument("--artifact", required=True, help="clean fixture artifact directory")
    ap.add_argument("--critic-cmd", default=None)
    ap.add_argument("--use-fixture-critic", action="store_true")
    ap.add_argument("--record", required=True, help="JSON with model_id, prompt_hash, checklist_hash")
    ap.add_argument("--critics", type=int, default=5)
    args = ap.parse_args()
    try:
        record = json.loads(Path(args.record).read_text(encoding="utf-8"))
        bank = json.loads(Path(args.bank).read_text(encoding="utf-8"))
        truth = json.loads(Path(args.ground_truth).read_text(encoding="utf-8"))
    except Exception as e:
        print(json.dumps({"error": f"cannot read inputs: {e}"}))
        return 2
    missing = [k for k in ("model_id", "prompt_hash", "checklist_hash") if not record.get(k)]
    if missing:
        print(json.dumps({"error": f"calibration record VOID: missing {missing}; records without model ID, prompt hash, and checklist hash are void"}))
        return 2
    violations = bank_hygiene_violations(bank)
    if violations:
        print(json.dumps({"error": f"bank hygiene VOID: seed insertions announce themselves "
                                    f"(seed_id or marker token in insertion text) for {violations}; "
                                    f"a marked bank measures marker visibility, not detection; refusing to score"}))
        return 2
    truth_by_id = {e["seed_id"]: e for e in truth["entries"]}
    # Custody: the oracle must live outside the ingested tree.
    custody_ok = True
    gt_resolved = Path(args.ground_truth).resolve()
    art_resolved = Path(args.artifact).resolve()
    if art_resolved in gt_resolved.parents or gt_resolved == art_resolved:
        custody_ok = False
        print("WARNING: ground truth resolves INSIDE the artifact under review; this run is INVALID "
              "(the panel can read the oracle). Hold the authoritative ground-truth copy outside the "
              "ingested tree and pass its path; see calibration/README.md.", file=sys.stderr)
    workdir = Path(tempfile.mkdtemp(prefix="seed-cal-"))
    copy = workdir / "review-copy"
    try:
        shutil.copytree(args.artifact, copy)
        for seed in bank["seeds"]:
            entry = truth_by_id.get(seed["seed_id"])
            if entry is None:
                print(json.dumps({"error": f"no ground-truth entry for {seed['seed_id']}; refusing to score"}))
                return 2
            rel = seed["target_file"]
            if Path(args.artifact).name == rel.split("/")[0]:
                rel = rel.split("/", 1)[1]
            target = copy / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            prior = target.read_text(encoding="utf-8") if target.is_file() else ""
            lines_before = 0 if not prior else prior.count("\n") + (0 if prior.endswith("\n") else 1)
            injected_line = lines_before + 1
            declared_line = int(entry["location"].rsplit(":", 1)[1])
            if injected_line != declared_line:
                print(json.dumps({"error": f"ground-truth drift on {seed['seed_id']}: the defect injects at line "
                                            f"{injected_line} of {seed['target_file']} but the ground truth declares "
                                            f"line {declared_line}; bank, fixture, or truth has drifted; refusing to score"}))
                return 2
            target.write_text(prior + seed["insertion"] + "\n", encoding="utf-8")
        per_critic = {}
        per_critic_partials = {}
        per_critic_lines = {}
        for i in range(1, args.critics + 1):
            cid = f"C{i}"
            if args.use_fixture_critic:
                lines = fixture_critic(copy, cid)
            elif args.critic_cmd:
                r = subprocess.run(args.critic_cmd.split() + [str(copy), cid], capture_output=True, text=True, timeout=300)
                lines = (r.stdout or "").splitlines()
            else:
                print(json.dumps({"error": "give --critic-cmd or --use-fixture-critic"}))
                return 2
            caught = {s["seed_id"] for s in bank["seeds"] if score(lines, s, truth_by_id[s["seed_id"]])}
            per_critic[cid] = caught
            partials = {}
            for s in bank["seeds"]:
                if s["seed_id"] in caught:
                    continue
                kind = score_partial(lines, s, truth_by_id[s["seed_id"]])
                if kind:
                    partials[s["seed_id"]] = kind
            per_critic_partials[cid] = partials
            per_critic_lines[cid] = lines
        union = set().union(*per_critic.values()) if per_critic else set()
        def rate(ids):
            return round(len(ids) / len(bank["seeds"]), 3) if bank["seeds"] else 0.0
        by_lens, by_sev = {}, {}
        for lens in sorted({s["lens"] for s in bank["seeds"]}):
            ids = {s["seed_id"] for s in bank["seeds"] if s["lens"] == lens}
            by_lens[lens] = {"caught": len(ids & union), "total": len(ids), "rate": round(len(ids & union) / len(ids), 3)}
        for sev in sorted({s["severity"] for s in bank["seeds"]}):
            ids = {s["seed_id"] for s in bank["seeds"] if s["severity"] == sev}
            by_sev[sev] = {"caught": len(ids & union), "total": len(ids), "rate": round(len(ids & union) / len(ids), 3)}
        report = {"calibration_record": record, "bank_version": bank.get("bank_version"),
                  "panel_union": {"caught": len(union), "total": len(bank["seeds"]), "rate": rate(union)},
                  "per_critic": {c: {"caught": len(v), "rate": rate(v)} for c, v in per_critic.items()},
                  "per_lens": by_lens, "per_severity": by_sev,
                  "missed": sorted(set(truth_by_id) - union),
                  "classification_partials": sorted({sid for pp in per_critic_partials.values() for sid, k in pp.items() if k == "classification-partial"}),
                  "localization_partials": sorted({sid for pp in per_critic_partials.values() for sid, k in pp.items() if k == "localization-partial"}),
                  "partials_note": "near misses are recorded for diagnosis and are never counted as catches",
                  "legacy_substring_score": {"caught": len({s["seed_id"] for ls in per_critic_lines.values() for s in bank["seeds"] if legacy_substring_caught(ls, s)}),
                                             "note": "the v1 substring rule, comparison only; it counts marker visibility, not detection"},
                  "custody_ok": custody_ok,
                  "valid": custody_ok,
                  "scoring": "a catch requires a finding line naming the target file, a line within "
                             f"{LINE_WINDOW} of the defect line, and the defect class token",
                  "status": "report-first: calibration earns gate status only with measured history. "
                            "When the fixture critic is used, its catch measures the harness plumbing "
                            "(injection, detection signatures, scoring), never panel skill."}
        print(json.dumps(report, indent=2))
        return 0 if union else 1
    finally:
        shutil.rmtree(workdir, ignore_errors=True)

if __name__ == "__main__":
    sys.exit(main())
